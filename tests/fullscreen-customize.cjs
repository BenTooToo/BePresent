const assert=require('node:assert/strict');
const {chromium}=require('playwright');

async function main() {
  const browser=await chromium.launch({channel:'msedge',headless:true});
  try {
    const context=await browser.newContext({locale:'zh-CN',viewport:{width:1440,height:1000},timezoneId:'Asia/Tokyo',permissions:['clipboard-read','clipboard-write']});
    const page=await context.newPage();
    const errors=[];page.on('pageerror',error=>errors.push(error.message));
    await page.clock.setFixedTime(new Date('2026-10-15T12:34:56Z'));
    await page.goto('http://127.0.0.1:4173/');
    await page.evaluate(()=>setCityPreview(Date.now()+3600000,cities[0],false));
    const worldTime=await page.locator('#clocks .digital').first().textContent();
    await page.locator('#settings-toggle').click();
    const modal=page.locator('#settings-panel'),preview=page.locator('#settings-preview');
    const rect=await modal.boundingBox();
    assert.deepEqual({x:rect.x,y:rect.y,width:rect.width,height:rect.height},{x:0,y:0,width:1440,height:1000});
    assert.equal(await modal.getAttribute('aria-modal'),'true');
    assert.equal(await page.locator('main').isVisible(),false);
    assert.equal(await page.locator('main').evaluate(el=>el.inert),true);
    assert.equal(await preview.locator('.digital').textContent(),'21:34:56');
    assert.equal(await preview.locator('.city').textContent(),'东京');
    assert.equal(await preview.locator('.country').textContent(),'日本');
    assert.equal(await preview.locator('.date').evaluate(el=>getComputedStyle(el).opacity),'1');
    assert.equal(await preview.locator('.digital').getAttribute('role'),null);
    await page.locator('[data-enabled="secondHand"]').uncheck();
    assert.equal(await preview.locator('.second').isVisible(),false);
    await page.locator('#numeral-count').selectOption('4',{force:true});
    await page.locator('#numeral-position').selectOption('inside',{force:true});
    assert.deepEqual(await preview.locator('.dial-numbers text').allTextContents(),['12','3','6','9']);
    assert.equal(await preview.locator('.dial-numbers').getAttribute('data-position'),'inside');
    await page.locator('[data-enabled="country"]').uncheck();
    assert.equal(await preview.locator('.country').isVisible(),false);
    await page.locator('[data-enabled="country"]').check();
    await page.locator('[data-language-select="primary-language"]').click();await page.locator(`.language-choice[data-language="${'en'}"]`).click();
    assert.equal(await preview.locator('.country').textContent(),'Japan');
    await page.locator('#multilingual').check();
    assert.deepEqual(await preview.locator('.city .translation-line').allTextContents(),['Tokyo','东京']);
    await page.clock.setFixedTime(new Date('2026-10-15T12:35:01Z'));
    await page.waitForFunction(()=>document.querySelector('#settings-preview .digital').textContent==='21:35:01');
    assert.equal(await page.locator('#clocks .digital').first().textContent(),worldTime);
    const last=page.locator('#developer-options');
    await last.focus();await page.keyboard.press('Tab');
    assert.equal(await page.locator('#settings-close').evaluate(el=>el===document.activeElement),true);
    await page.keyboard.press('Shift+Tab');
    assert.equal(await last.evaluate(el=>el===document.activeElement),true);
    await page.screenshot({path:'tests/customize-fullscreen-desktop.png'});
    await page.setViewportSize({width:390,height:844});
    await last.scrollIntoViewIfNeeded();
    const mobilePreview=await preview.boundingBox();
    assert(mobilePreview.x>180 && mobilePreview.y>=60 && mobilePreview.y<200);
    assert.equal(await page.locator('#settings-close').isVisible(),true);
    assert.equal(await modal.evaluate(el=>el.scrollWidth<=el.clientWidth),true);
    await page.screenshot({path:'tests/customize-fullscreen-mobile.png'});
    await page.keyboard.press('Escape');
    assert.equal(await modal.isVisible(),false);
    assert.equal(await preview.locator('.preview-clock').count(),0);
    assert.equal(await page.locator('main').evaluate(el=>el.inert),false);
    assert.equal(await page.locator('#clocks .digital').first().textContent(),worldTime);
    assert.equal(await page.evaluate(()=>document.body.style.overflow),'');
    // Success feedback is compact, green, borderless, and centered between clocks and add button.
    await page.setViewportSize({width:1440,height:1000});
    await page.locator('#capture').click();
    await page.locator('#capture-copy').click();
    await page.waitForFunction(()=>!document.getElementById('capture-preview').open);
    const toast=page.locator('#capture-status');
    await page.waitForTimeout(400);
    const appearance=await toast.evaluate(el=>{const s=getComputedStyle(el);return {color:s.color,fontSize:parseFloat(s.fontSize),border:s.borderTopWidth,background:s.backgroundColor,opacity:s.opacity,state:el.dataset.state};});
    assert.equal(appearance.color,'rgb(120, 206, 154)');assert(appearance.fontSize>=12 && appearance.fontSize<=14);
    assert.equal(appearance.border,'0px');assert.equal(appearance.background,'rgba(0, 0, 0, 0)');assert.equal(appearance.opacity,'1');assert.equal(appearance.state,'success');
    const toastBox=await toast.boundingBox(),clocksBox=await page.locator('#clocks').boundingBox(),addBox=await page.locator('#add').boundingBox();
    assert(toastBox.y>clocksBox.y+clocksBox.height && toastBox.y+toastBox.height<addBox.y);
    assert(Math.abs(toastBox.y+toastBox.height/2-(clocksBox.y+clocksBox.height+addBox.y)/2)<2);
    await page.screenshot({path:'tests/capture-success-toast.png'});
    await page.waitForFunction(()=>document.getElementById('capture-status').hidden,undefined,{timeout:5000});
    assert.deepEqual(errors,[]);
    console.log('PASS: fullscreen customization, live device-local preview independent of time exploration, immediate options/language preview, focus containment, sticky mobile preview, original-page restoration, compact green borderless feedback between clocks and add button.');
  } finally {await browser.close();}
}
main().catch(error=>{console.error(error);process.exitCode=1;});
